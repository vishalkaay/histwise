// Command histwise analyzes your shell history and suggests high-value aliases.
//
// Usage:
//
//	histwise                 analyze the detected shell history
//	histwise --json          emit machine-readable JSON
//	histwise --aliases       print a sourceable alias file
//	histwise --file PATH      analyze a specific history file
//
// It never phones home and never modifies your history.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/vishalkaaay/histwise/internal/analyze"
	"github.com/vishalkaaay/histwise/internal/history"
)

var version = "0.1.0"

// commonNoise lists programs rarely worth counting as "top programs".
var commonNoise = []string{"ls", "cd", "pwd", "clear", "exit", "echo"}

func main() {
	var (
		filePath   string
		shellName  string
		asJSON     bool
		asAliases  bool
		topN       int
		minCount   int
		includeAll bool
		showVer    bool
	)
	flag.StringVar(&filePath, "file", "", "path to a history file (default: auto-detect)")
	flag.StringVar(&shellName, "shell", "", "force shell format: bash|zsh|fish")
	flag.BoolVar(&asJSON, "json", false, "output JSON instead of a table")
	flag.BoolVar(&asAliases, "aliases", false, "output a sourceable alias file")
	flag.IntVar(&topN, "top", 15, "number of entries to show in each list")
	flag.IntVar(&minCount, "min", 3, "minimum occurrences for an alias suggestion")
	flag.BoolVar(&includeAll, "all", false, "include common noise commands (ls, cd, ...)")
	flag.BoolVar(&showVer, "version", false, "print version and exit")
	flag.Usage = usage
	flag.Parse()

	if showVer {
		fmt.Printf("histwise %s\n", version)
		return
	}

	src, ok := history.Locate(filePath, history.Shell(shellName), os.Getenv("HOME"))
	if !ok {
		fmt.Fprintln(os.Stderr, "histwise: could not find a shell history file.")
		fmt.Fprintln(os.Stderr, "Pass one explicitly, e.g.  histwise --file ~/.bash_history")
		os.Exit(1)
	}

	commands, err := history.Parse(src)
	if err != nil {
		fmt.Fprintf(os.Stderr, "histwise: reading %s: %v\n", src.Path, err)
		os.Exit(1)
	}

	opts := analyze.DefaultOptions()
	opts.TopN = topN
	opts.MinCount = minCount
	if !includeAll {
		opts.Ignore = commonNoise
	}
	rep := analyze.Analyze(commands, opts)

	switch {
	case asJSON:
		emitJSON(rep)
	case asAliases:
		emitAliases(rep, src.Shell)
	default:
		emitTable(rep, src)
	}
}

func usage() {
	fmt.Fprintf(os.Stderr, `histwise %s - learn from your shell history.

Analyzes bash, zsh and fish history to show your most-used commands and
suggest aliases ranked by the keystrokes they would actually save.

Usage: histwise [flags]

Flags:
`, version)
	flag.PrintDefaults()
	fmt.Fprintf(os.Stderr, "\nExamples:\n")
	fmt.Fprintf(os.Stderr, "  histwise                 # analyze auto-detected history\n")
	fmt.Fprintf(os.Stderr, "  histwise --aliases >> ~/.bash_aliases\n")
	fmt.Fprintf(os.Stderr, "  histwise --json | jq .alias_suggestions\n")
}

func emitJSON(rep analyze.Report) {
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	_ = enc.Encode(rep)
}

func emitAliases(rep analyze.Report, sh history.Shell) {
	fmt.Printf("# Generated by histwise. Review before sourcing.\n")
	fmt.Printf("# Add to your shell rc file, e.g.  source ~/.histwise_aliases\n\n")
	// Stable, friendly ordering by alias name.
	sug := append([]analyze.AliasSuggestion(nil), rep.Suggestions...)
	sort.Slice(sug, func(i, j int) bool { return sug[i].Alias < sug[j].Alias })
	for _, s := range sug {
		cmd := s.Command
		if sh == history.Fish {
			fmt.Printf("alias %s %q  # saves ~%d keystrokes\n", s.Alias, cmd, s.Saved)
		} else {
			fmt.Printf("alias %s=%q  # saves ~%d keystrokes\n", s.Alias, cmd, s.Saved)
		}
	}
	if len(sug) == 0 {
		fmt.Printf("# No strong alias candidates found (try --min 2).\n")
	}
}

func emitTable(rep analyze.Report, src history.Source) {
	bold := color("1")
	dim := color("2")
	cyan := color("36")
	green := color("32")
	reset := colorReset()

	fmt.Printf("%shistwise%s  %s(%s: %s)%s\n\n", bold, reset, dim, src.Shell, src.Path, reset)
	fmt.Printf("Analyzed %s%d%s commands, %s%d%s unique.\n\n",
		green, rep.TotalCommands, reset, green, rep.UniqueCommands, reset)

	fmt.Printf("%sTop programs%s\n", bold, reset)
	maxProg := 0
	for _, p := range rep.TopPrograms {
		if len(p.Program) > maxProg {
			maxProg = len(p.Program)
		}
	}
	maxCount := 1
	for _, p := range rep.TopPrograms {
		if p.Count > maxCount {
			maxCount = p.Count
		}
	}
	for _, p := range rep.TopPrograms {
		bar := sparkBar(p.Count, maxCount, 24)
		fmt.Printf("  %s%-*s%s  %s%-24s%s %4d\n",
			cyan, maxProg, p.Program, reset, dim, bar, reset, p.Count)
	}

	fmt.Printf("\n%sAlias suggestions%s %s(ranked by keystrokes saved)%s\n", bold, reset, dim, reset)
	if len(rep.Suggestions) == 0 {
		fmt.Printf("  %sNone found. Try --min 2 or --top 30.%s\n", dim, reset)
	}
	for _, s := range rep.Suggestions {
		fmt.Printf("  %s%-6s%s = %s%-40s%s %sx%d, ~%d saved%s\n",
			green, s.Alias, reset, "", truncate(s.Command, 40), reset,
			dim, s.Count, s.Saved, reset)
	}
	fmt.Printf("\n%sTip:%s histwise --aliases >> ~/.bash_aliases\n", bold, reset)
}

func sparkBar(v, max, width int) string {
	if max <= 0 {
		return ""
	}
	n := v * width / max
	if n < 1 && v > 0 {
		n = 1
	}
	return strings.Repeat("#", n)
}

func truncate(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	if n <= 1 {
		return string(r[:n])
	}
	return string(r[:n-1]) + "\u2026"
}

// color returns an ANSI escape only when stdout is a terminal and NO_COLOR is
// unset; otherwise it returns an empty string so piped output stays clean.
func color(code string) string {
	if !useColor() {
		return ""
	}
	return "\x1b[" + code + "m"
}

func colorReset() string {
	if !useColor() {
		return ""
	}
	return "\x1b[0m"
}

func useColor() bool {
	if _, ok := os.LookupEnv("NO_COLOR"); ok {
		return false
	}
	fi, err := os.Stdout.Stat()
	if err != nil {
		return false
	}
	return (fi.Mode() & os.ModeCharDevice) != 0
}
